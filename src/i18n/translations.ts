export function getSavedLanguage(): AppLanguage {
  const saved = localStorage.getItem('cypher24_lang') as AppLanguage;
  if (saved && ['it', 'en', 'fr', 'es', 'zh', 'ru'].includes(saved)) {
    return saved;
  }
  // Try browser language detection
  const navLang = navigator.language?.slice(0, 2)?.toLowerCase();
  if (['it', 'en', 'fr', 'es', 'zh', 'ru'].includes(navLang)) {
    return navLang as AppLanguage;
  }
  return 'it';
}

export function saveLanguage(lang: AppLanguage): void {
  localStorage.setItem('cypher24_lang', lang);
}

export function t(key: string, lang: AppLanguage): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.it;
  return dict[key] || TRANSLATIONS.it[key] || key;
}

export function formatExpiryText(hours: number, minutes: number, seconds: number, lang: AppLanguage): string {
  const prefix = t('expiresIn', lang);
  if (hours >= 1) {
    return `${prefix} ${hours}h`;
  }
  if (minutes >= 1) {
    return `${prefix} ${minutes}m`;
  }
  return `${prefix} ${seconds}s`;
}
